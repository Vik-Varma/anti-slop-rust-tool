fn words(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    for raw in text.split_whitespace() {
        let lower = raw.to_ascii_lowercase();
        if lower.starts_with("...") || lower == "…" {
            out.push("...".to_string());
        }
        let cleaned: String = lower.chars().filter(|c| c.is_alphanumeric()).collect();
        if !cleaned.is_empty() {
            out.push(cleaned);
        }
    }
    out
}

fn find_placeholder(text: &str) -> Option<String> {
    let w = words(text);
    for pat in PLACEHOLDER_PATTERNS {
        let (anchored, pat) = match pat.split_first() {
            Some((&"^", rest)) => (true, rest),
            _ => (false, *pat),
        };
        let matches_at =
            |i: usize| w.len() >= i + pat.len() && w[i..i + pat.len()].iter().zip(pat).all(|(a, b)| a == b);
        let hit = if anchored { matches_at(0) } else { (0..w.len()).any(matches_at) };
        if hit {
            return Some(pat.join(" "));
        }
    }
    None
}

impl Rule for PlaceholderComment {
    fn meta(&self) -> &'static RuleMeta {
        &PLACEHOLDER
    }
    fn check(&self, input: &Input, sink: &mut Sink) {
        let ctx = input.ctx;
        // Doc comments are skipped: their code examples legitimately elide code.
        for c in ctx.comments().iter().filter(|c| !c.is_doc) {
            if !ctx.is_production_line(c.line) {
                continue;
            }
            if let Some(p) = find_placeholder(&c.text) {
                sink.emit(
                    c.line,
                    c.column,
                    format!("placeholder comment (\"{p}\"): the code here is likely incomplete"),
                );
            }
        }
    }
}

/// Groups consecutive own-line, non-doc line comments into blocks.
fn comment_blocks<'c>(ctx: &'c FileContext) -> Vec<Vec<&'c Comment>> {
    let mut blocks: Vec<Vec<&Comment>> = Vec::new();
    for c in ctx.comments() {
        if c.is_doc || !c.own_line {
            continue;
        }
        if c.is_block {
            blocks.push(vec![c]);
            continue;
        }
        match blocks.last_mut() {
            Some(b) if !b[0].is_block && b.last().is_some_and(|l| l.end_line + 1 == c.line && l.column == c.column) => {
                b.push(c)
            }
            _ => blocks.push(vec![c]),
        }
    }
    blocks
}

const DIRECTIVES: &[&str] = &["anti-slop:", "rustfmt::", "clippy::", "safety:", "noqa", "spdx-license", "copyright"];

fn looks_like_code(text: &str) -> bool {
    let trimmed = text.trim();
    if trimmed.is_empty() {
        return false;
    }
    let lower = trimmed.to_ascii_lowercase();
    if DIRECTIVES.iter().any(|d| lower.contains(d)) {
        return false;
    }
    // Commented-out code ends statements and blocks; prose rarely does.
    let code_lines = trimmed
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .filter(|l| {
            l.ends_with(';')
                || l.ends_with('{')
                || l.ends_with('}')
                || l.ends_with("},")
                || l.starts_with("let ")
                || l.starts_with("fn ")
                || l.starts_with("use ")
                || l.starts_with("#[")
        })
        .count();
    if code_lines == 0 {
        return false;
    }
    // Must parse as Rust items or as a sequence of statements.
    if syn::parse_str::<syn::File>(trimmed).is_ok_and(|f| !f.items.is_empty()) {
        return true;
    }
    match syn::parse_str::<syn::Block>(&format!("{{\n{trimmed}\n}}")) {
        Ok(block) => block.stmts.iter().any(|s| !is_trivial_stmt(s)),
        Err(_) => false,
    }
}

/// A lone path or literal (`foo`, `42`) parses as a statement but is usually prose.
fn is_trivial_stmt(s: &syn::Stmt) -> bool {
    matches!(s, syn::Stmt::Expr(syn::Expr::Path(_) | syn::Expr::Lit(_), None))
}

impl Rule for CommentedOutCode {
    fn meta(&self) -> &'static RuleMeta {
        &COMMENTED_OUT
    }
    fn check(&self, input: &Input, sink: &mut Sink) {
        let ctx = input.ctx;
        for block in comment_blocks(ctx) {
            if !ctx.is_production_line(block[0].line) {
                continue;
            }
            // Code inside ``` fences, or introduced by a line ending in ':', is an
            // illustration, not dead code.
            let mut illustrative = vec![false; block.len()];
            let mut in_fence = false;
            for (k, c) in block.iter().enumerate() {
                let t = c.text.trim();
                if t.starts_with("```") {
                    in_fence = !in_fence;
                    illustrative[k] = true;
                } else {
                    illustrative[k] = in_fence;
                }
            }
            // Comment blocks often mix prose with code: find maximal runs that parse.
            let mut i = 0;
            while i < block.len() {
                if illustrative[i] || (i > 0 && block[i - 1].text.trim_end().ends_with(':')) {
                    i += 1;
                    continue;
                }
                let end = (i..block.len()).find(|&k| illustrative[k]).unwrap_or(block.len());
                let found = (i..end).rev().find(|&j| {
                    let text: String = block[i..=j].iter().map(|c| c.text.as_str()).collect::<Vec<_>>().join("\n");
                    looks_like_code(&text)
                });
                let Some(j) = found else {
                    i += 1;
                    continue;
                };
                let (first, last) = (block[i], block[j]);
                let n = last.end_line - first.line + 1;
                let what = if n == 1 { "line".to_string() } else { format!("{n} lines") };
                sink.emit(
                    first.line,
                    first.column,
                    format!("commented-out code ({what}); delete it, version control keeps history"),
                );
                i = j + 1;
            }
        }
    }
}

fn satd_marker(text: &str) -> Option<&'static str> {
    for marker in ["TODO", "FIXME", "HACK", "XXX"] {
        let mut rest = text;
        while let Some(idx) = rest.find(marker) {
            let before = rest[..idx].chars().next_back();
            let after = rest[idx + marker.len()..].chars().next();
            let boundary_before = before.is_none_or(|c| !c.is_alphanumeric() && c != '_');
            let boundary_after = after.is_none_or(|c| !c.is_alphanumeric() && c != '_');
            if boundary_before && boundary_after {
                return Some(marker);
            }
            rest = &rest[idx + marker.len()..];
        }
    }
    None
}

impl Rule for SatdComment {
    fn meta(&self) -> &'static RuleMeta {
        &SATD
    }
    fn check(&self, input: &Input, sink: &mut Sink) {
        let ctx = input.ctx;
        for c in ctx.comments() {
            if !ctx.is_production_line(c.line) {
                continue;
            }
            if let Some(m) = satd_marker(&c.text) {
                sink.emit(c.line, c.column, format!("`{m}` marker: self-admitted technical debt"));
            }
        }
    }
}

const STOPWORDS: &[&str] = &[
    "the", "a", "an", "of", "to", "and", "or", "for", "in", "on", "with", "from", "by", "it", "its", "this", "that",
    "is", "be", "we", "our", "now", "then", "here", "value", "variable", "result", "new", "into", "as", "at", "all",
];

/// Comment verbs that are "said" by syntax rather than identifiers.
fn verb_matches(word: &str, code: &str) -> bool {
    let has = |s: &str| code.contains(s);
    match word {
        "create" | "construct" | "initialize" | "initialise" | "init" | "instantiate" | "make" => {
            has("new") || has("default") || has("from") || has("vec!") || has("with_capacity")
        }
        "increment" => has("+= 1"),
        "decrement" => has("-= 1"),
        "return" => has("return") || !code.trim_end().ends_with(';'),
        "call" | "invoke" => has("("),
        "check" | "verify" | "ensure" => has("if ") || has("assert") || has("is_") || has("ensure"),
        "loop" | "iterate" | "iter" => has("for ") || has("while ") || has("iter"),
        "print" | "log" => has("print") || has("log") || has("info!") || has("debug!"),
        "set" | "assign" | "store" | "update" | "save" => has("="),
        "convert" => has("into") || has("from") || has(" as ") || has("parse"),
        "add" | "append" | "push" | "insert" => has("push") || has("insert") || has("+") || has("extend"),
        "get" | "fetch" | "retrieve" | "read" | "obtain" => has("."),
        "clone" | "copy" => has("clone") || has("copy"),
        "unwrap" => has("unwrap"),
        "sort" => has("sort"),
        _ => false,
    }
}

fn stem(w: &str) -> String {
    let w = w.to_ascii_lowercase();
    for suffix in ["ing", "ed", "es", "s"] {
        if w.len() > suffix.len() + 2
            && let Some(s) = w.strip_suffix(suffix)
        {
            return s.to_string();
        }
    }
    w
}

fn identifier_words(code: &str) -> HashSet<String> {
    let mut out = HashSet::new();
    let mut cur = String::new();
    let mut prev_lower = false;
    let flush = |cur: &mut String, out: &mut HashSet<String>| {
        if !cur.is_empty() {
            out.insert(stem(cur));
            cur.clear();
        }
    };
    for ch in code.chars() {
        if ch.is_alphanumeric() {
            if ch.is_uppercase() && prev_lower {
                flush(&mut cur, &mut out);
            }
            prev_lower = ch.is_lowercase();
            cur.push(ch);
        } else {
            flush(&mut cur, &mut out);
            prev_lower = false;
        }
    }
    flush(&mut cur, &mut out);
    out
}

/// Does `comment` only restate `code`?
pub fn restates(comment: &str, code: &str) -> bool {
    let words: Vec<String> = comment
        .split(|c: char| !c.is_alphanumeric() && c != '\'')
        .filter(|w| !w.is_empty())
        .map(|w| w.to_ascii_lowercase())
        .collect();
    if words.len() < 2 || words.len() > 8 || comment.contains('?') {
        return false;
    }
    let content: Vec<&String> = words.iter().filter(|w| !STOPWORDS.contains(&w.as_str())).collect();
    if content.is_empty() {
        return false;
    }
    let ids = identifier_words(code);
    let mut matched_identifier = false;
    for w in &content {
        let s = stem(w);
        if ids.contains(&s) {
            matched_identifier = true;
        } else if !verb_matches(w, code) && !verb_matches(&s, code) {
            return false;
        }
    }
    matched_identifier
}

impl Rule for RedundantComment {
    fn meta(&self) -> &'static RuleMeta {
        &REDUNDANT
    }
    fn check(&self, input: &Input, sink: &mut Sink) {
        let ctx = input.ctx;
        for block in comment_blocks(ctx) {
            if block.len() != 1 || block[0].is_block {
                continue;
            }
            let c = block[0];
            let next = c.end_line + 1;
            if !ctx.is_production_line(c.line) || !ctx.lexed.line_has_code(next) {
                continue;
            }
            let code = ctx.line_text(next).trim();
            // Only single-line statements.
            if !(code.ends_with(';') || code.ends_with(',')) || code.starts_with("//") {
                continue;
            }
            if restates(&c.text, code) {
                sink.emit(c.line, c.column, "comment restates the next line without adding information");
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::rules::testing::{check_rule, lines};

    #[test]
    fn placeholders() {
        let src = r#"
fn a() {
    // ... rest of the code
    // In a real implementation, you would query the database.
    // Simplified for brevity
    // This keeps the existing order.
    // the rest of the items are skipped
    // skip the rest of the function
    // Special case for brevity, since most hit this path.
    // existing code ...
}
/// // your code here
fn b() {}
"#;
        assert_eq!(lines(&check_rule("placeholder-comment", src)), vec![3, 4, 5, 10]);
    }

    #[test]
    fn commented_out_code() {
        let src = r#"
fn a(x: u32) -> u32 {
    // let y = x * 2;
    // println!("{}", y);
    // This explains why x is returned.
    // See foo() for details.
    // TODO: handle overflow
    // if x > 3 {
    //     return 4;
    // }
    x
}
// fn old() {}
// Example:
// let z = 1;
// ```
// let w = 2;
// ```
"#;
        assert_eq!(lines(&check_rule("commented-out-code", src)), vec![3, 8, 13]);
    }

    #[test]
    fn satd() {
        let src = "// TODO: fix\n// todo lowercase\n// FIXME(bob) later\n// TODOS are fine\nfn a() {}\n";
        assert_eq!(lines(&check_rule("satd-comment", src)), vec![1, 3]);
    }

    #[test]
    fn restating() {
        assert!(restates(" Increment the counter", "counter += 1;"));
        assert!(restates(" Create a new vector", "let mut vector = Vec::new();"));
        assert!(restates(" Parse the config file", "let config = parse_config_file(path)?;"));
        assert!(restates(" return the users", "users"));
        assert!(!restates(" Retry because the server drops idle connections", "client.retry();"));
        assert!(!restates(" Safe: index checked above", "let v = items[idx];"));
        assert!(!restates(" 2 extra slots for the header", "let n = len + 2;"));
    }

    #[test]
    fn redundant_comment_rule() {
        let src = "fn a(mut counter: u32) {\n    // increment counter\n    counter += 1;\n    // avoid overflow on 32-bit targets\n    counter += 1;\n}\n";
        assert_eq!(lines(&check_rule("redundant-comment", src)), vec![2]);
    }
}
